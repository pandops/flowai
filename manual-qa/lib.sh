# --- JSON encoding --------------------------------------------------------

mq::jq_available() {
  command -v jq >/dev/null 2>&1
}

# Detect whether a value is already valid JSON (object / array / string /
# number / bool / null). Used by mq::json_encode to pick --argjson vs
# --arg so nested objects survive intact.
mq::json_value_is_json() {
  local val="${1:-}"
  case "$val" in
    true|false|null) return 0 ;;
  esac
  if [[ "$val" =~ ^-?[0-9]+([.][0-9]+)?([eE][+-]?[0-9]+)?$ ]]; then
    return 0
  fi
  case "$val" in
    \"*) return 0 ;; # already a JSON-quoted string
  esac
  case "$val" in
    \{*\}|\[*\]|\{*|\[*)
      # Object or array literal; verify with python (jq is unavailable
      # at this layer when this helper is invoked).
      python3 -c "import json,sys; json.loads(sys.argv[1])" "$val" >/dev/null 2>&1
      return $?
      ;;
  esac
  return 1
}

mq::json_encode() {
  # mq::json_encode <key=value>...
  # Emits a single JSON object on stdout. Each value that is already
  # valid JSON is passed through with --argjson; everything else is
  # passed with --arg so jq's safe-string quoting applies.
  local -a jq_args=()
  local -a py_kvs=()
  local kv key val

  for kv in "$@"; do
    key="${kv%%=*}"
    val="${kv#*=}"
    if mq::jq_available; then
      if mq::json_value_is_json "$val"; then
        jq_args+=(--argjson "$key" "$val")
      else
        jq_args+=(--arg "$key" "$val")
      fi
    else
      py_kvs+=("$kv")
    fi
  done

  if mq::jq_available; then
    jq -n '$ARGS.named' "${jq_args[@]}" 2>/dev/null || mq::fail "jq encode"
    return 0
  fi

  # python3 fallback — same contract; values are validated with
  # json.loads so nested objects survive intact.
  python3 - "${py_kvs[@]}" <<'PY' || mq::fail "python3 encode"
import json, sys
out = {}
for kv in sys.argv[1:]:
    if "=" not in kv:
        print(f"bad kv: {kv}", file=sys.stderr); sys.exit(2)
    k, v = kv.split("=", 1)
    try:
        out[k] = json.loads(v)
    except Exception:
        out[k] = v
print(json.dumps(out, separators=(",", ":")))
PY
}

# --- container runtime ----------------------------------------------------

# Podman only. The manual QA flow requires rootless Podman.
mq::detect_runtime() {
  if command -v podman >/dev/null 2>&1; then
    printf 'podman\n'
    return 0
  fi
  mq::fail "podman is required on PATH; this manual QA flow does not support Docker"
}

# Run a runtime subprocess with bounded stdout/stderr. We never eval the
# command; every arg is array-passed.
mq::runtime_spawn() {
  local rt="${1:-}"
  shift
  [[ -n "$rt" ]] || mq::fail "runtime_spawn: runtime is required"
  local stdout_tmp stderr_tmp
  stdout_tmp="$(mktemp)" || mq::fail "mktemp stdout"
  stderr_tmp="$(mktemp)" || mq::fail "mktemp stderr"
  chmod 0600 "$stdout_tmp" "$stderr_tmp"

  set +o errexit
  "$rt" "$@" >"$stdout_tmp" 2>"$stderr_tmp"
  local rc=$?
  set -o errexit
  if [[ $rc -ne 0 ]]; then
    local stderr_trimmed
    stderr_trimmed="$(head -c 4096 "$stderr_tmp")"
    rm -f "$stdout_tmp" "$stderr_tmp"
    mq::fail "$rt $* exited code=$rc stderr=$stderr_trimmed"
  fi
  cat "$stdout_tmp"
  rm -f "$stdout_tmp" "$stderr_tmp"
}

# Generate a fresh postgres password from 16 random bytes / 32 hex characters;
# no quoted/escaped values leak into the env file because the runtime puts it
# on the command line with --env KEY=value (no shell).
mq::random_password() {
  head -c 16 /dev/urandom | od -An -tx1 | tr -d ' \n'
}

mq::runtime_run_postgres() {
  # mq::runtime_run_postgres <runtime> <name> <password> <db>
  # Starts a TLS-enabled postgres:16 with loopback-only publication,
  # a tmpfs data directory, and SELinux-safe :Z bind mounts. Persists
  # the container id, the host port, and the container name so cleanup
  # can find the artifact even after this function returns.
  local rt="${1:-}" name="${2:-}" password="${3:-}" db="${4:-flowai}"
  [[ -n "$rt" && -n "$name" && -n "$password" && -n "$db" ]] \
    || mq::fail "runtime_run_postgres args"

  local tls_dir
  tls_dir="$(mq::state_path state/pg-tls)"
  install -d -m 0700 "$tls_dir" || mq::fail "mkdir pg-tls"

  mq::runtime_stage_pg_tls "$tls_dir"

  # Invoke the staged entrypoint through /bin/bash. The whole tls-dir
  # is mounted as one private SELinux volume (:ro,Z); the entrypoint
  # path inside the container is /etc/flowai/pg-tls/custom-entrypoint.sh.
  local cid
  cid="$(mq::runtime_spawn "$rt" run \
    --detach \
    --rm \
    --name "$name" \
    --publish "127.0.0.1::5432" \
    --tmpfs "/var/lib/postgresql/data:rw" \
    --volume "$tls_dir:/etc/flowai/pg-tls:ro,Z" \
    --entrypoint /bin/bash \
    --env "POSTGRES_PASSWORD=$password" \
    --env "POSTGRES_DB=$db" \
    docker.io/library/postgres:16 \
    /etc/flowai/pg-tls/custom-entrypoint.sh postgres -c ssl=on -c ssl_cert_file=/var/lib/postgresql/server.crt -c ssl_key_file=/var/lib/postgresql/server.key
  )" || mq::fail "postgres run"
  cid="${cid//[[:space:]]/}"
  printf '%s\n' "$cid" > "$(mq::state_path state/pg.cid)"
  chmod 0600 "$(mq::state_path state/pg.cid)"
  printf '%s\n' "$name" > "$(mq::state_path state/pg.name)"
  chmod 0600 "$(mq::state_path state/pg.name)"

  local host_port=""
  local deadline=$(( $(date +%s) + 30 ))
  while [[ $(date +%s) -lt $deadline ]]; do
    local out inspect_rc
    set +o errexit
    out="$("$rt" inspect \
      --format '{{(index (index .NetworkSettings.Ports "5432/tcp") 0).HostPort}}' \
      "$cid" 2>/dev/null)"
    inspect_rc=$?
    set -o errexit
    if [[ $inspect_rc -eq 0 && "$out" =~ ^[0-9]+$ ]] && [[ "$out" -gt 0 ]]; then
      host_port="$out"
      break
    fi
    sleep 0.2
  done
  [[ -n "$host_port" ]] || mq::fail "postgres: OS-assigned host port never resolved for container $cid"
  printf '%s\n' "$host_port" > "$(mq::state_path state/pg.host_port)"
  chmod 0600 "$(mq::state_path state/pg.host_port)"
  printf '%s\n%s\n' "$cid" "$host_port"
}

mq::runtime_stage_pg_tls() {
  # mq::runtime_stage_pg_tls <tls-dir>
  # Copies the cert + key from the runtime state certs dir into tls-dir
  # and writes a custom entrypoint that copies them into
  # /var/lib/postgresql/ with postgres:postgres ownership and 0600/0644
  # mode, then execs the original docker-entrypoint.sh.
  local dir="${1:-}"
  [[ -n "$dir" ]] || mq::fail "runtime_stage_pg_tls requires a directory"
  install -d -m 0700 "$dir"

  cp -f "$(mq::state_path state/certs/pg-server.crt)" "$dir/server.crt"
  cp -f "$(mq::state_path state/certs/pg-server.key)" "$dir/server.key"
  chmod 0644 "$dir/server.crt"
  chmod 0600 "$dir/server.key"

  cat >"$dir/custom-entrypoint.sh" <<'ENTRYPOINT'
#!/bin/bash
set -eu
SRC_DIR="/etc/flowai/pg-tls"
DST_CERT="/var/lib/postgresql/server.crt"
DST_KEY="/var/lib/postgresql/server.key"
cp -f "${SRC_DIR}/server.crt" "${DST_CERT}"
cp -f "${SRC_DIR}/server.key" "${DST_KEY}"
chown postgres:postgres "${DST_CERT}" "${DST_KEY}"
chmod 0644 "${DST_CERT}"
chmod 0600 "${DST_KEY}"
exec /usr/local/bin/docker-entrypoint.sh "$@"
ENTRYPOINT
  chmod 0755 "$dir/custom-entrypoint.sh"
}

mq::runtime_remove() {
  # mq::runtime_remove <runtime> <container-id>
  local rt="${1:-}" cid="${2:-}"
  [[ -n "$rt" && -n "$cid" ]] || mq::fail "runtime_remove args"
  set +o errexit
  "$rt" rm --force "$cid" >/dev/null 2>&1 || true
  set -o errexit
}

# --- process supervision --------------------------------------------------

mq::pid_is_alive() {
  local pid="${1:-}"
  [[ -n "$pid" ]] || return 1
  kill -0 "$pid" 2>/dev/null
}

# mq::pid_identity_check <pid> <expected-binary-substring>
# Returns 0 when the pid's /proc/PID/cmdline contains the expected
# binary substring. Used to refuse to terminate a process whose PID
# has been reused for a different executable.
mq::pid_identity_check() {
  local pid="${1:-}" expected="${2:-}"
  [[ -n "$pid" && -n "$expected" ]] || return 1
  [[ -r "/proc/$pid/cmdline" ]] || return 1
  local cmdline
  cmdline="$(tr '\0' ' ' <"/proc/$pid/cmdline" 2>/dev/null || true)"
  [[ "$cmdline" == *"$expected"* ]]
}

mq::terminate_pid() {
  # mq::terminate_pid <pid> <timeout-seconds> <expected-binary-substring>
  # Refuses to signal a process whose /proc/PID/cmdline does not match
  # the expected binary substring.
  local pid="${1:-}" timeout_s="${2:-10}" expected="${3:-}"
  [[ -n "$pid" ]] || mq::fail "terminate_pid requires a pid"
  if ! mq::pid_is_alive "$pid"; then
    return 0
  fi
  if [[ -n "$expected" ]] && ! mq::pid_identity_check "$pid" "$expected"; then
    mq::fail "pid=$pid cmdline does not match expected '$expected'; refusing to kill (likely PID reuse)"
  fi
  set +o errexit
  kill -TERM "$pid" 2>/dev/null || true
  local end=$(( $(date +%s) + timeout_s ))
  while [[ $(date +%s) -lt $end ]]; do
    if ! mq::pid_is_alive "$pid"; then
      set -o errexit
      return 0
    fi
    sleep 0.2
  done
  kill -KILL "$pid" 2>/dev/null || true
  sleep 0.5
  if mq::pid_is_alive "$pid"; then
    set -o errexit
    mq::fail "process pid=$pid refused to exit within ${timeout_s}s after SIGTERM + SIGKILL"
  fi
  set -o errexit
}

# --- wait helpers ---------------------------------------------------------

mq::wait_http_https() {
  # mq::wait_http_https <url> <cacert> <cert> <key> <timeout-seconds>
  local url="${1:-}" cacert="${2:-}" cert="${3:-}" key="${4:-}" timeout_s="${5:-30}"
  local end=$(( $(date +%s) + timeout_s ))
  local last_err=""
  while [[ $(date +%s) -lt $end ]]; do
    local out
    set +o errexit
    out="$(curl --silent --show-error --fail-with-body \
      --cacert "$cacert" --cert "$cert" --key "$key" \
      --max-time 3 "$url" 2>&1)"
    local rc=$?
    set -o errexit
    if [[ $rc -eq 0 ]]; then
      printf '%s\n' "$out"
      return 0
    fi
    last_err="$out"
    sleep 0.5
  done
  mq::fail "wait_http_https: $url never responded within ${timeout_s}s (last error: ${last_err:0:256})"
}

mq::wait_http_plain() {
  # mq::wait_http_plain <url> <timeout-seconds>
  # Plaintext wait helper used to probe the executor's own platform
  # health surface, which is intentionally plaintext (the executor
  # binds 127.0.0.1:8020 without TLS; mTLS is reserved for the State
  # Registry). Uses --fail-with-body so an HTTP 4xx/5xx response is
  # treated as not-ready rather than silently accepted.
  local url="${1:-}" timeout_s="${2:-30}"
  local end=$(( $(date +%s) + timeout_s ))
  local last_err=""
  while [[ $(date +%s) -lt $end ]]; do
    local out
    set +o errexit
    out="$(curl --silent --show-error --fail-with-body --max-time 3 "$url" 2>&1)"
    local rc=$?
    set -o errexit
    if [[ $rc -eq 0 ]]; then
      printf '%s\n' "$out"
      return 0
    fi
    last_err="$out"
    sleep 0.5
  done
  mq::fail "wait_http_plain: $url never responded within ${timeout_s}s (last error: ${last_err:0:256})"
}
