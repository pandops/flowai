#!/usr/bin/env bash
# lib.sh — shared helpers for the manual QA flow.
#
# Source this file from every other manual-qa/*.sh script:
#
#   source "$(dirname "$0")/lib.sh"
#
# Public surface (functions only — no globals are exported except
# FLOWAI_MANUAL_QA_RUN_DIR):
#
#   Strict mode + tracing
#     mq::enter_strict_mode       — enable errexit/pipefail/nounset + umask 0077
#     mq::trace                   — print a timestamped log line to stderr
#     mq::fail                    — print a diagnostic + exit 1
#     mq::require_cmd             — fail when $1 is not on PATH
#     mq::require_rootless_podman — fail when XDG_RUNTIME_DIR/podman/podman.sock is absent
#
#   Local dotenv loader (NO source / NO eval)
#     mq::load_dotenv <path>      — parse a single KEY=VALUE file safely
#     mq::load_manual_qa_dotenv   — load <manual-qa>/.env when present
#
#   Runtime state (under ${FLOWAI_MANUAL_QA_RUN_DIR:-/tmp/flowai-manual-qa})
#     mq::state_init              — validate the root path, create the protected tree
#     mq::state_path <rel>        — absolute path inside the runtime state dir
#     mq::state_write_env         — write a key=value line to state/env.sh with %q
#     mq::state_require_env       — verify owner/mode and source state/env.sh
#
#   Certificate issuance (OpenSSL, ephemeral CA, GNU `timeout`-bounded)
#     mq::openssl_run <args...>   — run openssl under `timeout` with a stdout cap
#     mq::ca_init                 — generate a private CA
#     mq::issue_server_cert       — issue a localhost+127.0.0.1 serverAuth cert
#     mq::issue_client_cert       — issue a clientAuth cert with role/team/serial subject
#
#   Backend HTTP curl wrappers
#     mq::curl_http_json          — GET/POST/PUT JSON over backend HTTP
#     mq::curl_admin_post         — POST /admin/* with trusted admin context
#     mq::curl_listener_post      — POST /v1/tasks with listener context
#     mq::curl_gateway_get        — GET with trusted Gateway context
#
#   JSON helpers
#     mq::json_encode             — emit a JSON object via jq (--argjson for JSON, --arg for strings)
#     mq::jq_available            — return 0 when jq is on PATH
#
#   Plain HTTP wait helper (the executor binds 127.0.0.1:8020 plaintext)
#     mq::wait_http_plain
#
#   Container runtime helpers (Podman only)
#     mq::detect_runtime          — print 'podman' or fail
#     mq::runtime_run_postgres    — start a TLS-enabled Postgres 16 container, loopback-only, :Z
#     mq::runtime_remove          — remove a container by id (best-effort, idempotent)
#     mq::runtime_stage_pg_tls    — write the staged cert + key + custom entrypoint
#     mq::random_password         — 16 random bytes / 32 hex characters
#
#   Process supervision
#     mq::pid_is_alive            — return 0 when the pid is running
#     mq::pid_identity_check      — refuse to act on a PID whose cmdline does not match
#     mq::terminate_pid           — SIGTERM (with identity check) then SIGKILL
#
#   Wait helpers
#     mq::wait_http_plain         — wait for a plaintext http endpoint to respond
#
# Security boundaries enforced here:
#   * runtime state dir is mode 0700; every state file is mode 0600
#   * private keys are mode 0600 by construction
#   * runtime state is generated by THIS script only; nothing is sourced
#     from an attacker-controlled arbitrary path; the env export file is
#     owner-checked + mode-checked before being sourced
#   * the env export file is emitted through Bash %q so values never
#     become shell-active (no eval)
#   * no curl -k, no InsecureSkipVerify, no plaintext fallback for the
#     State Registry surfaces
#   * openssl subprocesses are bounded by GNU `timeout` and an output cap
#   * process termination is gated on a /proc/PID/cmdline check so a
#     stale PID file cannot cause a wrong process to be killed

# --- strict mode -----------------------------------------------------------

mq::enter_strict_mode() {
  set -o errexit
  set -o pipefail
  set -o nounset
  set -o errtrace
  # Owner-only default. Every file this script creates uses install -m
  # explicitly; umask 0077 is defense in depth.
  umask 0077
  IFS=$' \t\n'
}

mq::trace() {
  # mq::trace <phase> <message>
  printf '[%s] [%s] %s\n' "$(date -u '+%Y-%m-%dT%H:%M:%SZ')" "${1:-run}" "${2:-}" >&2
}

mq::fail() {
  # mq::fail <message>
  mq::trace "fatal" "${1:-unspecified failure}"
  exit 1
}

mq::require_cmd() {
  local cmd="${1:-}"
  if [[ -z "$cmd" ]]; then
    mq::fail "mq::require_cmd called without an argument"
  fi
  if ! command -v "$cmd" >/dev/null 2>&1; then
    mq::fail "required command not found on PATH: $cmd"
  fi
}

mq::require_rootless_podman() {
  local uid
  uid="$(id -u)"
  local runtime_dir="${XDG_RUNTIME_DIR:-/run/user/$uid}"
  local sock="$runtime_dir/podman/podman.sock"
  if [[ ! -S "$sock" ]]; then
    mq::fail "rootless Podman socket not found at $sock (XDG_RUNTIME_DIR=$runtime_dir); enable with 'systemctl --user enable --now podman.socket' or set XDG_RUNTIME_DIR"
  fi
  local owner_uid
  owner_uid="$(stat -c '%u' "$sock" 2>/dev/null || true)"
  if [[ "$owner_uid" != "$uid" ]]; then
    mq::fail "rootless Podman socket at $sock is owned by uid=$owner_uid, expected $uid"
  fi
}

# --- local dotenv loader (NO source / NO eval) ---------------------------

# mq::load_dotenv <path>
# Parse a simple KEY=VALUE dotenv file into the current shell.
#
# Hard requirements (enforced):
#   * NEVER sources the file; NEVER evals it; NEVER uses `set -a`.
#   * Refuses symlink files.
#   * Refuses non-current-owner files.
#   * Refuses any mode that grants group / world access (must be 0600
#     or 0400; 0600 is the canonical mode for manual-qa/.env).
#   * Refuses files containing NUL bytes (binary content rejected).
#   * Refuses lines with carriage returns (CR).
#   * Refuses malformed lines, unknown keys, and invalid identifiers.
#   * Refuses values containing $ / ` / \ in unquoted form (no
#     parameter / command expansion).
#   * Refuses trailing junk after a closing quote.
#
# Supported value forms:
#   * unquoted literal (no shell metacharacters allowed)
#   * single-quoted literal '...'   (no expansion inside)
#   * double-quoted literal "..."   (no expansion inside)
#   * empty unquoted / empty quoted value
#
# Precedence: a shell variable that is already set (whether exported
# from the parent environment or assigned earlier in the script) takes
# precedence over the .env file. An explicitly empty exported variable
# is detected via `${var+X}` and is also honoured as a precedence win.
mq::load_dotenv() {
  local path="${1:-}"
  [[ -n "$path" ]] || mq::fail "mq::load_dotenv requires a path"

  if [[ ! -e "$path" ]]; then
    mq::fail "mq::load_dotenv: $path does not exist"
  fi
  if [[ -L "$path" ]]; then
    mq::fail "mq::load_dotenv: $path is a symlink; refusing to parse"
  fi
  if [[ ! -f "$path" ]]; then
    mq::fail "mq::load_dotenv: $path is not a regular file"
  fi

  local my_uid owner_uid mode
  my_uid="$(id -u)"
  owner_uid="$(stat -c '%u' "$path" 2>/dev/null || true)"
  mode="$(stat -c '%a' "$path" 2>/dev/null || true)"
  if [[ -z "$owner_uid" || -z "$mode" ]]; then
    mq::fail "mq::load_dotenv: stat failed for $path"
  fi
  if [[ "$owner_uid" != "$my_uid" ]]; then
    mq::fail "mq::load_dotenv: $path is owned by uid=$owner_uid, expected $my_uid"
  fi
  case "$mode" in
    600|400) ;;
    *) mq::fail "mq::load_dotenv: $path has mode=$mode (must be 0600 or 0400); group/world-writable refused" ;;
  esac

  # NUL bytes cannot appear in a well-formed dotenv file. Reject them
  # up front so a hostile value cannot smuggle binary content past the
  # line-based reader. The implementation translates NULs to '@' with
  # tr and then greps for '@' — a NUL-terminated C-string trick used
  # by grep -F cannot match an empty pattern and would otherwise
  # produce a false positive on every clean text file.
  if LC_ALL=C tr '\0' '@' <"$path" | grep -q '@'; then
    mq::fail "mq::load_dotenv: $path contains NUL bytes (binary content rejected)"
  fi

  local lineno=0 raw key value stripped
  while IFS= read -r raw || [[ -n "$raw" ]]; do
    lineno=$((lineno + 1))

    # Reject Windows-style line endings (the read above would have
    # preserved the trailing CR inside `raw`).
    if [[ "$raw" == *$'\r'* ]]; then
      mq::fail "mq::load_dotenv: $path:$lineno contains carriage return (Windows line endings rejected)"
    fi

    # Strip leading whitespace only; trailing whitespace on a data line
    # is rejected as malformed because real whitespace inside an
    # unquoted value is ambiguous.
    stripped="${raw#"${raw%%[![:space:]]*}"}"

    # Blank line or full-line comment.
    if [[ -z "$stripped" ]]; then
      continue
    fi
    if [[ "$stripped" == \#* ]]; then
      continue
    fi

    if [[ ! "$raw" =~ ^([A-Za-z_][A-Za-z0-9_]*)=(.*)$ ]]; then
      mq::fail "mq::load_dotenv: $path:$lineno malformed line (expected KEY=VALUE): $raw"
    fi
    key="${BASH_REMATCH[1]}"
    value="${BASH_REMATCH[2]}"

    # Fixed allow-list. Anything else is a hard error.
    case "$key" in
      OPENHANDS_LLM_MODEL|OPENHANDS_LLM_API_KEY|OPENHANDS_LLM_USAGE_ID|\
OPENHANDS_LLM_BASE_URL|OPENHANDS_AGENT_PROFILE_ID|PROMPT|\
FLOWAI_MANUAL_QA_RUN_DIR|FLOWAI_REPO_ROOT|DOCKER_SOCKET_PATH|\
OPENHANDS_HOST_PORT_START|OPENHANDS_HOST_PORT_END|OPENHANDS_WORKSPACE|\
RUN_ALL_NO_CLEANUP)
        ;;
      *) mq::fail "mq::load_dotenv: $path:$lineno unknown key '$key' (not in allow-list)" ;;
    esac

    # Parse the value form. Inside single / double quotes the content
    # is purely literal; no $, no `, no \ escape processing.
    case "$value" in
      \"\")
        value=""
        ;;
      \"*)
        if [[ "${#value}" -lt 2 || "$value" != *'"'* ]]; then
          mq::fail "mq::load_dotenv: $path:$lineno unterminated double quote"
        fi
        if [[ "${value: -1}" != '"' ]]; then
          mq::fail "mq::load_dotenv: $path:$lineno trailing junk after double quote"
        fi
        value="${value:1:-1}"
        ;;
      \'\')
        value=""
        ;;
      \'*)
        if [[ "${#value}" -lt 2 || "$value" != *\'* ]]; then
          mq::fail "mq::load_dotenv: $path:$lineno unterminated single quote"
        fi
        if [[ "${value: -1}" != \' ]]; then
          mq::fail "mq::load_dotenv: $path:$lineno trailing junk after single quote"
        fi
        value="${value:1:-1}"
        ;;
      *)
        # Unquoted literal. Reject any character that could enable
        # parameter / command expansion or backslash escape.
        if [[ "$value" == *\$\(* || "$value" == *\$\{* || "$value" == *\`* || "$value" == *\\* ]]; then
          mq::fail "mq::load_dotenv: $path:$lineno unquoted value contains expansion or escape character"
        fi
        ;;
    esac

    # Precedence: anything already set in this shell wins, including
    # explicitly empty exported variables. We must use indirect
    # expansion (${!key+X}) so the check tests the variable *named by*
    # $key — a plain ${key+X} would test the local variable `key`
    # itself, which is always set inside this function and would mask
    # every .env value.
    if [[ -n "${!key+X}" ]]; then
      continue
    fi

    # Export so the value is visible to child processes started by the
    # operational scripts (Executor, State Registry, Postgres).
    export "$key=$value"
  done < "$path"
}

# mq::load_manual_qa_dotenv <script-dir>
# Convenience wrapper: load <script-dir>/.env into the current shell
# when the file exists. Quietly does nothing when the file is absent
# so callers can invoke this unconditionally.
mq::load_manual_qa_dotenv() {
  local script_dir="${1:-}"
  [[ -n "$script_dir" ]] || mq::fail "mq::load_manual_qa_dotenv requires a script directory"
  local dotenv_file="$script_dir/.env"
  if [[ -f "$dotenv_file" && ! -L "$dotenv_file" ]]; then
    mq::load_dotenv "$dotenv_file"
  fi
}

# --- runtime state --------------------------------------------------------

mq::state_init() {
  # An unset or empty value intentionally uses the documented default.
  if [[ -z "${FLOWAI_MANUAL_QA_RUN_DIR:-}" ]]; then
    FLOWAI_MANUAL_QA_RUN_DIR="/tmp/flowai-manual-qa"
  fi

  # Validate the selected root path. We refuse:
  #   - "/"
  #   - exact '.' or '..' path segments (which could traverse unexpectedly)
  #   - symlink at the root (would let a hostile symlink redirect all
  #     later file writes outside the chosen root)
  if [[ "$FLOWAI_MANUAL_QA_RUN_DIR" == "/" ]]; then
    mq::fail "FLOWAI_MANUAL_QA_RUN_DIR must be a non-root directory; got '$FLOWAI_MANUAL_QA_RUN_DIR'"
  fi
  case "/$FLOWAI_MANUAL_QA_RUN_DIR/" in
    */./*|*/../*) mq::fail "FLOWAI_MANUAL_QA_RUN_DIR contains a traversal segment: $FLOWAI_MANUAL_QA_RUN_DIR" ;;
  esac
  if [[ -L "$FLOWAI_MANUAL_QA_RUN_DIR" ]]; then
    mq::fail "FLOWAI_MANUAL_QA_RUN_DIR is a symlink: $FLOWAI_MANUAL_QA_RUN_DIR (refusing to follow)"
  fi
  export FLOWAI_MANUAL_QA_RUN_DIR

  if [[ ! -d "$FLOWAI_MANUAL_QA_RUN_DIR" ]]; then
    install -d -m 0700 "$FLOWAI_MANUAL_QA_RUN_DIR" || mq::fail "create $FLOWAI_MANUAL_QA_RUN_DIR"
  fi
  # Tighten permissions on every entry (covers re-runs into a previous dir).
  chmod 0700 "$FLOWAI_MANUAL_QA_RUN_DIR"

  local sub
  for sub in state certs logs pids bin pg-tls; do
    if [[ -L "$FLOWAI_MANUAL_QA_RUN_DIR/$sub" ]]; then
      mq::fail "runtime state subdirectory is a symlink: $FLOWAI_MANUAL_QA_RUN_DIR/$sub (refusing to follow)"
    fi
    install -d -m 0700 "$FLOWAI_MANUAL_QA_RUN_DIR/$sub" \
      || mq::fail "create $FLOWAI_MANUAL_QA_RUN_DIR/$sub"
  done
}

mq::state_path() {
  # mq::state_path <relative-path>
  local rel="${1:-}"
  [[ -n "$rel" ]] || mq::fail "mq::state_path requires a relative path"
  # Reject absolute paths or exact '.' / '..' segments that could escape
  # or ambiguously resolve within the runtime root.
  case "$rel" in
    /*) mq::fail "mq::state_path: relative path must not be absolute: $rel" ;;
  esac
  case "/$rel/" in
    */./*|*/../*) mq::fail "mq::state_path: relative path must not contain '.' or '..' segments: $rel" ;;
  esac
  printf '%s/%s\n' "${FLOWAI_MANUAL_QA_RUN_DIR:?}" "$rel"
}

mq::state_write_env() {
  # mq::state_write_env <key> <value>
  # The key MUST be a valid shell identifier; the value is emitted via
  # Bash %q so a hostile value cannot become a shell command. The
  # resulting file is mode 0600, owned by the current user, and is
  # the ONLY path other scripts ever source.
  local key="${1:-}"
  local value="${2:-}"
  [[ -n "$key" ]] || mq::fail "mq::state_write_env requires a key"
  if [[ ! "$key" =~ ^[A-Za-z_][A-Za-z0-9_]*$ ]]; then
    mq::fail "mq::state_write_env: '$key' is not a valid shell identifier"
  fi

  local env_file
  env_file="$(mq::state_path state/env.sh)"
  local tmp
  tmp="$(mktemp "$(mq::state_path state)/env.sh.XXXXXX")"
  chmod 0600 "$tmp"
  if [[ -f "$env_file" ]]; then
    # grep returns 1 normally when no previous declaration for this key exists.
    grep -v -E "^declare -g ${key}=" "$env_file" >"$tmp" || true
  fi
  printf 'declare -g %s=%q\n' "$key" "$value" >>"$tmp"
  mv -f "$tmp" "$env_file"
  chmod 0600 "$env_file"
}

mq::state_require_env() {
  local env_file
  env_file="$(mq::state_path state/env.sh)"
  if [[ ! -f "$env_file" ]]; then
    mq::fail "runtime env file missing at $env_file; run 01-prepare.sh first"
  fi
  if [[ -L "$env_file" ]]; then
    mq::fail "$env_file is a symlink; refusing to source"
  fi
  local owner_uid mode my_uid
  owner_uid="$(stat -c '%u' "$env_file" 2>/dev/null || true)"
  mode="$(stat -c '%a' "$env_file" 2>/dev/null || true)"
  my_uid="$(id -u)"
  if [[ "$owner_uid" != "$my_uid" ]]; then
    mq::fail "$env_file is owned by uid=$owner_uid, expected $my_uid"
  fi
  if [[ "$mode" != "600" ]]; then
    mq::fail "$env_file has mode=$mode (must be 0600)"
  fi
  # shellcheck disable=SC1090
  source "$env_file"
}

# --- certificate issuance (GNU timeout-bounded) ---------------------------

MQ_OPENSSL_DEADLINE_MS="${MQ_OPENSSL_DEADLINE_MS:-15000}"
MQ_OPENSSL_OUTPUT_CAP_BYTES="${MQ_OPENSSL_OUTPUT_CAP_BYTES:-16384}"

mq::openssl_run() {
  # mq::openssl_run <args...>
  local -a args=("$@")
  local bin
  bin="$(command -v openssl || true)"
  [[ -n "$bin" ]] || mq::fail "openssl binary not found on PATH"
  command -v timeout >/dev/null 2>&1 || mq::fail "GNU 'timeout' is required by mq::openssl_run but was not found on PATH"

  local stdout_tmp stderr_tmp
  stdout_tmp="$(mktemp)" || mq::fail "mktemp stdout"
  stderr_tmp="$(mktemp)" || mq::fail "mktemp stderr"
  chmod 0600 "$stdout_tmp" "$stderr_tmp"

  # timeout sends SIGTERM at the deadline and escalates to SIGKILL after
  # an additional grace window so a stuck openssl can never hang the
  # whole QA flow. GNU timeout accepts only s/m/h/d units, so convert
  # the millisecond cap to whole seconds (rounded up to at least 1s).
  local deadline_s
  deadline_s="$(( (MQ_OPENSSL_DEADLINE_MS + 999) / 1000 ))"
  [[ "$deadline_s" -ge 1 ]] || deadline_s=1

  set +o errexit
  timeout --kill-after=2 "${deadline_s}s" "$bin" "${args[@]}" \
    >"$stdout_tmp" 2>"$stderr_tmp"
  local rc=$?
  set -o errexit

  if [[ $rc -ne 0 ]]; then
    local stderr_trimmed
    stderr_trimmed="$(head -c 4096 "$stderr_tmp")"
    rm -f "$stdout_tmp" "$stderr_tmp"
    mq::fail "openssl ${args[*]} exited code=$rc stderr=$stderr_trimmed"
  fi
  local out_bytes
  out_bytes="$(wc -c <"$stdout_tmp")"
  if (( out_bytes > MQ_OPENSSL_OUTPUT_CAP_BYTES )); then
    : >"$stdout_tmp"
  fi
  cat "$stdout_tmp"
  rm -f "$stdout_tmp" "$stderr_tmp"
}

mq::ca_init() {
  # mq::ca_init <ca-dir>
  local dir="${1:-}"
  [[ -n "$dir" ]] || mq::fail "mq::ca_init requires a directory"
  install -d -m 0700 "$dir" || mq::fail "mkdir $dir"

  mq::openssl_run genrsa -out "$dir/ca.key" 2048 >/dev/null
  chmod 0600 "$dir/ca.key"

  mq::openssl_run req -x509 -new -batch \
    -key "$dir/ca.key" \
    -out "$dir/ca.crt" \
    -days 1 \
    -subj "/CN=flowai-manual-qa-ca/OU=qa" >/dev/null
  chmod 0644 "$dir/ca.crt"
}

mq::openssl_server_ext() {
  cat <<'EOF'
extendedKeyUsage = serverAuth
subjectAltName = @alt_names
[alt_names]
DNS.1 = localhost
IP.1 = 127.0.0.1
EOF
}

mq::openssl_client_ext() {
  cat <<'EOF'
extendedKeyUsage = clientAuth
EOF
}

# Build a Bash-quoted /N=v1/N=v2/... subject line from key=value pairs.
# Empty values are skipped (so admin gets no O=, no serialNumber=).
mq::build_subject() {
  local -a parts=()
  local kv
  for kv in "$@"; do
    [[ -n "$kv" ]] || continue
    local key="${kv%%=*}"
    local val="${kv#*=}"
    [[ -n "$val" ]] || continue
    parts+=("/${key}=${val}")
  done
  local IFS=
  printf '%s' "${parts[*]}"
}

mq::issue_server_cert() {
  # mq::issue_server_cert <ca-dir> <out-dir> <name>
  local ca_dir="${1:-}" out_dir="${2:-}" name="${3:-server}"
  [[ -n "$ca_dir" && -n "$out_dir" && -n "$name" ]] || mq::fail "issue_server_cert args"

  install -d -m 0700 "$out_dir" || mq::fail "mkdir $out_dir"

  mq::openssl_run genrsa -out "$out_dir/$name.key" 2048 >/dev/null
  chmod 0600 "$out_dir/$name.key"

  mq::openssl_run req -new -batch \
    -key "$out_dir/$name.key" \
    -out "$out_dir/$name.csr" \
    -subj "/CN=flowai-manual-qa-$name/OU=qa" >/dev/null

  local ext="$out_dir/$name.ext"
  mq::openssl_server_ext >"$ext"
  chmod 0600 "$ext"

  mq::openssl_run x509 -req \
    -in "$out_dir/$name.csr" \
    -CA "$ca_dir/ca.crt" \
    -CAkey "$ca_dir/ca.key" \
    -CAcreateserial \
    -out "$out_dir/$name.crt" \
    -days 1 \
    -extfile "$ext" >/dev/null
  chmod 0644 "$out_dir/$name.crt"
  rm -f "$out_dir/$name.csr"
}

mq::issue_client_cert() {
  # mq::issue_client_cert <ca-dir> <out-dir> <name> <subject-kv...>
  local ca_dir="${1:-}" out_dir="${2:-}" name="${3:-}"
  shift 3
  [[ -n "$ca_dir" && -n "$out_dir" && -n "$name" ]] || mq::fail "issue_client_cert args"

  install -d -m 0700 "$out_dir" || mq::fail "mkdir $out_dir"

  mq::openssl_run genrsa -out "$out_dir/$name.key" 2048 >/dev/null
  chmod 0600 "$out_dir/$name.key"

  local subject
  subject="$(mq::build_subject "$@")"

  mq::openssl_run req -new -batch \
    -key "$out_dir/$name.key" \
    -out "$out_dir/$name.csr" \
    -subj "$subject" >/dev/null

  local ext="$out_dir/$name.ext"
  mq::openssl_client_ext >"$ext"
  chmod 0600 "$ext"

  mq::openssl_run x509 -req \
    -in "$out_dir/$name.csr" \
    -CA "$ca_dir/ca.crt" \
    -CAkey "$ca_dir/ca.key" \
    -CAcreateserial \
    -out "$out_dir/$name.crt" \
    -days 1 \
    -extfile "$ext" >/dev/null
  chmod 0644 "$out_dir/$name.crt"
  rm -f "$out_dir/$name.csr"
}

# --- backend HTTP curl wrappers ------------------------------------------

mq::curl_http_json() {
  # mq::curl_http_json <method> <url> <body-file-or-empty> [header ...]
  # Prints "<HTTP_STATUS>\n<body>" on stdout. Uses --fail-with-body so a
  # non-2xx response is surfaced as an explicit error rather than a
  # silent empty body. The caller must never pass -k / insecure.
  local method="${1:-GET}" url="${2:-}" body="${3:-}"
  shift 3
  [[ -n "$url" ]] || mq::fail "curl_http_json: url is required"

  local -a curl_args=(
    --silent
    --show-error
    --fail-with-body
    --request "$method"
    --url "$url"
    --connect-timeout 5
    --max-time 30
    --write-out '\n%{http_code}'
    --header 'Accept: application/json'
  )
  local header
  for header in "$@"; do
    curl_args+=(--header "$header")
  done
  if [[ -n "$body" ]]; then
    curl_args+=(--header 'Content-Type: application/json' --data-binary "@$body")
  fi

  local resp status
  resp="$(curl "${curl_args[@]}")"
  status="${resp##*$'\n'}"
  body="${resp%$'\n'*}"
  printf '%s\n%s' "$status" "$body"
}

mq::curl_admin_post() {
  # mq::curl_admin_post <url> <body-file>
  mq::curl_http_json POST "$1" "$2" \
    "X-FlowAI-Role: admin" \
    "X-FlowAI-Admin-Subject: system-admin-local" \
    "X-FlowAI-Request-Id: manual-admin-$RANDOM"
}

mq::curl_listener_post() {
  # mq::curl_listener_post <url> <body-file>
